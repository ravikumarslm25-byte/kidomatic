import { Router } from "express";
import { requireAudience, requireRole } from "../../core/auth/auth.middleware.js";
import * as c from "./platform.controller.js";
import * as billing from "./billing.controller.js";
import * as crm from "./platform-crm.controller.js";
const r = Router();
r.use(requireAudience("platform"), requireRole("Super Admin", "Platform Support"));
r.get("/resellers", c.listResellers);
r.post("/resellers", c.createReseller);
r.patch("/resellers/:id", c.updateReseller);
r.get("/schools", c.listSchools);
r.post("/schools", c.createSchool);
r.get("/summary", c.summary);
r.get("/plans", c.plans);
// Sales / licences / invoices
r.post("/sales", billing.createSale);
r.get("/licenses", billing.listLicenses);
r.post("/licenses/:id/activate", billing.activateLicense);
r.post("/licenses/:id/suspend", billing.suspendLicense);
r.get("/invoices", billing.listInvoices);
r.get("/invoices/:id", billing.getInvoice);
r.post("/invoices/:id/send", billing.sendInvoice);
r.post("/invoices/:id/pay", billing.payInvoice);
// CRM & ops modules (SaaS Admin: Leads, Quotations, Transactions, Users, Support)
r.get("/leads", crm.listLeads);
r.post("/leads", crm.createLead);
r.patch("/leads/:id", crm.updateLead);
r.get("/quotations", crm.listQuotations);
r.post("/quotations", crm.createQuotation);
r.patch("/quotations/:id", crm.updateQuotation);
r.post("/quotations/:id/send", crm.sendQuotation);
r.post("/quotations/:id/convert", crm.convertQuotation);
r.get("/transactions", crm.listTransactions);
r.get("/users", crm.listUsers);
r.post("/users", crm.createUser);
r.patch("/users/:id", crm.updateUser);
r.get("/tickets", crm.listTickets);
r.patch("/tickets/:id", crm.updateTicket);
r.post("/tickets/:id/reply", crm.replyTicket);
export default r;
